import { RelayCast } from "@relaycast/sdk"
const baseUrl = "http://127.0.0.1:8787"
const tag = String(Date.now() % 100000)
const ws: any = await RelayCast.createWorkspace("smoke-" + tag, { baseUrl })
console.log("WORKSPACE", Object.keys(ws), JSON.stringify(ws).slice(0, 200))
const relay = new RelayCast({ apiKey: ws.apiKey, baseUrl })
const a: any = await relay.agents.register({ name: "alpha" + tag, type: "agent" } as any)
const b: any = await relay.agents.register({ name: "beta" + tag, type: "agent" } as any)
console.log("AGENT", Object.keys(a), JSON.stringify(a).slice(0, 200))
relay.on.messageCreated((e: any) => console.log("WS messageCreated", JSON.stringify(e).slice(0, 400)))
relay.on.dmReceived((e: any) => console.log("WS dmReceived", JSON.stringify(e).slice(0, 400)))
relay.on.connected(() => console.log("WS connected"))
relay.connect()
const A: any = await relay.reconnect({ apiToken: a.token })
const B: any = await relay.reconnect({ apiToken: b.token })
await new Promise(r => setTimeout(r, 800))
const ch = await A.channels.create({ name: "wormhole" + tag }).catch((e: any) => console.log("create err", e.message))
await B.channels.join("wormhole" + tag).catch((e: any) => console.log("join err", e.message))
const sent = await A.send("#wormhole" + tag, "Is anyone there? It has been four million years.")
console.log("SEND RESULT", JSON.stringify(sent).slice(0, 300))
const dm = await A.dm("beta" + tag, "Psst. A human just arrived on my world.")
console.log("DM RESULT", JSON.stringify(dm).slice(0, 300))
await new Promise(r => setTimeout(r, 2000))
relay.disconnect()
process.exit(0)
